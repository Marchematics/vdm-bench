"""Re-score the ana-vec 10M submission with the stratified range plan.

The plan change only touches the range-count estimator; the coverage and join answers of the
submission were validated separately (10M certified coverage pass, IVF join recall 0.9985) and
are reused byte-for-byte.  So this script:

  1. recomputes range_count with ``reference.range_stratified`` (Neyman-allocated strata),
  2. keeps the existing coverage / join lists,
  3. adds the estimator's query cost delta to the submission's reported cost,
  4. re-scores with ``core.eval_analytics`` and rewrites the 10M leaderboard JSON + markdown.

The previous predictions are kept as ``predictions.presstrat.json`` so the ablation row
(``ana-vec-sampling``, uniform sampling at the same budget) stays exactly reproducible.
"""
import json
import os
import shutil
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from vdmbench import core          # noqa: E402
sys.path.insert(0, os.path.join(ROOT, "baselines"))
import reference as ref            # noqa: E402

DATA = os.path.expanduser("~/vdm/data")
DS = "sift10m"
SUB = "ana-vec"


def main():
    wl = core.load_analytics(os.path.join(ROOT, "workloads", DS)) if hasattr(core, "load_analytics") \
        else None
    if wl is None:
        z = np.load(os.path.join(ROOT, "workloads", DS, "analytics.npz"))
        wl = {k: z[k] for k in z.files}
        wl["n"] = int(wl["n"])
    X, _ = core.load_dataset(DATA, DS, wl["n"])
    X = np.ascontiguousarray(X.astype(np.float32), dtype=np.float32)
    Q = np.ascontiguousarray(wl["queries"].astype(np.float32))
    radii = wl["radii"]
    print(f"n={len(X)} queries={len(Q)} radii={np.round(radii, 1).tolist()}", flush=True)

    path = os.path.join(ROOT, "submissions", SUB, "predictions.json")
    backup = path.replace(".json", ".presstrat.json")
    if not os.path.exists(backup):
        shutil.copyfile(path, backup)
    # always build from the pristine (pre-stratification) submission so re-running is
    # idempotent: the coverage/join lists and their cost are reused unchanged.
    old = json.load(open(backup))

    est, range_cost = ref.range_stratified(X, Q, radii, seed=0)
    old_range_cost = float(old.get("range_cost_hint", 1.0e7))   # uniform S=0.01n x 100 queries
    new = dict(old)
    new["range_count"] = est.tolist()
    new["cost"] = float(old["cost"]) - old_range_cost + range_cost
    print(f"range cost {old_range_cost:.3e} -> {range_cost:.3e}; "
          f"total cost {old['cost']:.4e} -> {new['cost']:.4e}", flush=True)

    m = core.eval_analytics(new, wl, DATA, DS)
    print("new ana-vec metrics:", json.dumps(m, indent=1), flush=True)

    json.dump(new, open(path, "w"))

    lb_path = os.path.join(ROOT, "results_remote", f"leaderboard_{DS}.json")
    if not os.path.exists(lb_path):
        lb_path = os.path.join(ROOT, "results", f"leaderboard_{DS}.json")
    rows = json.load(open(lb_path))
    for r in rows:
        if r["task"] == "analytics" and r["submission"] == SUB:
            for k, v in m.items():
                r[k] = v
    json.dump(rows, open(lb_path, "w"), indent=2)

    md = os.path.join(ROOT, f"leaderboard_{DS}.md")
    with open(md, "w") as f:
        f.write(f"# VDM-Bench reference leaderboard — {DS}\n\n")
        f.write("Generated by `run_reference.py`; numbers are CPU-only reference runs.\n\n")
        for task in ["analytics", "quality", "serving"]:
            f.write(f"## {task}\n\n")
            for r in rows:
                if r["task"] != task:
                    continue
                keys = [k for k in r if k not in ("task", "submission")]
                f.write(f"- **{r['submission']}**: "
                        + ", ".join(f"{k}={r[k]:.4g}" for k in keys) + "\n")
            f.write("\n")
    print("wrote", path, lb_path, md, flush=True)


if __name__ == "__main__":
    main()
