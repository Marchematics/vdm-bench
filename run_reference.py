"""Generate reference submissions, score them, and write leaderboard.json/.md.

Leaderboards are *merged*, never clobbered: running ``--only serving`` updates the serving
rows in ``leaderboard_<dataset>.md`` (and, for SIFT, in the canonical ``leaderboard.md``)
while leaving every other task's rows byte-identical. That is the fix for the historical
failure where a single-task regeneration silently emptied the other sections.
"""
import argparse
import json
import os

import numpy as np

from baselines import reference as ref
from vdmbench import core

TASKS = ["analytics", "quality", "serving"]


def load_wl(task, wl_dir):
    if task == "analytics":
        z = np.load(os.path.join(wl_dir, "analytics.npz"))
        return {k: z[k] for k in z.files}
    if task == "quality":
        wl = json.load(open(os.path.join(wl_dir, "quality.json")))
        wl["contract"] = core.QUALITY_CONTRACT   # published contract, enforced by eval_quality
        return wl
    z = np.load(os.path.join(wl_dir, "serving.npz"))
    meta = json.load(open(os.path.join(wl_dir, "serving_meta.json")))
    wl = {"hard": z["hard"], "arrival": z["arrival"], "tenants": meta["tenants"],
          "cores": meta["cores"], "rhos": meta.get("rhos", [meta.get("rho")])}
    for k in ("score", "arrival_eval", "deadline", "recall_req"):
        if k in z.files:
            wl[k] = z[k]
    for k in ("skew", "rates_qps", "hard_deadline_scale"):
        if k in meta:
            wl[k] = meta[k]
    return wl


def _format_row(r):
    keys = [k for k in r if k not in ("task", "submission") and not str(k).startswith("_")]
    return f"- **{r['submission']}**: " + ", ".join(f"{k}={r[k]:.4g}" for k in keys) + "\n"


def _parse_sections(path):
    """Split a leaderboard markdown into (header lines, {task: section lines}, task order)."""
    header, sections, order = [], {}, []
    cur = None
    with open(path) as f:
        for line in f:
            if line.startswith("## "):
                cur = line[3:].strip()
                order.append(cur)
                sections[cur] = []
            elif cur is None:
                header.append(line)
            else:
                sections[cur].append(line)
    return header, sections, order


def merge_leaderboard(path, rows, dataset):
    """Replace only the sections present in ``rows``; leave every other section untouched."""
    if os.path.exists(path):
        header, sections, order = _parse_sections(path)
    else:
        header = [f"# VDM-Bench reference leaderboard — {dataset}\n", "\n",
                  "Generated by `run_reference.py`; numbers are CPU-only reference runs.\n", "\n"]
        sections, order = {}, []
    for task in TASKS:
        if task not in sections:
            sections[task] = ["\n"]
            order.append(task)
    by_task = {}
    for r in rows:
        by_task.setdefault(r["task"], []).append(r)
    for task, rs in by_task.items():
        sections[task] = ["\n"] + [_format_row(r) for r in rs] + ["\n"]
    out = list(header)
    for task in TASKS + [t for t in order if t not in TASKS]:
        if task not in sections:
            continue
        out.append(f"## {task}\n")
        out.extend(sections[task])
    with open(path, "w") as f:
        f.writelines(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-root", required=True)
    ap.add_argument("--workloads", default="workloads")
    ap.add_argument("--out", default="results")
    ap.add_argument("--full", action="store_true",
                    help="include the optional AnaVec/VecProf analytics/quality submissions")
    ap.add_argument("--dataset", default="sift", choices=["sift", "sift10m", "mnist", "scifact"])
    ap.add_argument("--only", default="all",
                    choices=["all", "analytics", "quality", "serving"])
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    rows = []

    wdir = os.path.join(a.workloads, a.dataset) if os.path.isdir(os.path.join(a.workloads, a.dataset)) else a.workloads
    if a.only in ("all", "analytics") and os.path.exists(os.path.join(wdir, "analytics.npz")):
        wa = load_wl("analytics", wdir)
        analytics = [("exact-oracle", ref.analytics_exact),
                     ("uniform-sampling", lambda w: ref.analytics_sampling(a.data_root, w, dataset=a.dataset)),
                     ("ivf-plan", lambda w: ref.analytics_ivf(a.data_root, w, dataset=a.dataset))]
        if a.full:
            analytics.append(("ana-vec", lambda w: ref.analytics_anavec(a.data_root, w, dataset=a.dataset)))
            # ablation: the same planner with plain sampling (no exact IVF prefix)
            analytics.append(("ana-vec-sampling", lambda w: ref.analytics_anavec(
                a.data_root, w, dataset=a.dataset, n_probe_lists=0, sample_n=12000)))
        for name, fn in analytics:
            print(f"[analytics] {name}: building submission ...", flush=True)
            pred = fn(wa)
            print(f"[analytics] {name}: scoring ...", flush=True)
            m = core.eval_analytics(pred, wa, a.data_root, dataset=a.dataset)
            rows.append({"task": "analytics", "submission": name, **m})
            os.makedirs(os.path.join("submissions", name), exist_ok=True)
            json.dump(pred, open(os.path.join("submissions", name, "predictions.json"), "w"))

    if a.only in ("all", "quality") and os.path.exists(os.path.join(wdir, "quality.json")):
        wq = load_wl("quality", wdir)
        quality = [("quality-oracle", ref.quality_exact), ("quality-naive", ref.quality_naive)]
        if a.full:
            quality.append(("vecprof-ref", lambda w: ref.quality_vecprof(a.data_root, w)))
        for name, fn in quality:
            pred = fn(wq)
            m = core.eval_quality(pred, wq)
            rows.append({"task": "quality", "submission": name, **m})
            os.makedirs(os.path.join("submissions", name), exist_ok=True)
            json.dump(pred, open(os.path.join("submissions", name, "predictions.json"), "w"))

    if a.only in ("all", "serving") and os.path.exists(os.path.join(wdir, "serving.npz")):
        ws = load_wl("serving", wdir)
        preds = {}
        for name, fn in [("serving-static", ref.serving_static),
                         ("serving-adaptive", ref.serving_adaptive),
                         ("serving-signal", ref.serving_signal),
                         ("serving-edf", ref.serving_edf)]:
            preds[name] = fn(ws)
        # the quota submission is tuned first; the oracle warm-starts from it (so the oracle
        # is an upper bound on the quota space by construction)
        preds["serving-vecslo"] = ref.serving_vecslo(ws, verbose=True)
        preds["serving-oracle"] = ref.serving_oracle(ws, warm=preds["serving-vecslo"], verbose=True)
        for name in ["serving-static", "serving-adaptive", "serving-signal", "serving-edf",
                     "serving-vecslo", "serving-oracle"]:
            pred = preds[name]
            m = core.eval_serving(pred, ws)
            rows.append({"task": "serving", "submission": name, **m})
            os.makedirs(os.path.join("submissions", name), exist_ok=True)
            json.dump(pred, open(os.path.join("submissions", name, "predictions.json"), "w"))

    with open(os.path.join(a.out, f"leaderboard_{a.dataset}.json"), "w") as f:
        json.dump(rows, f, indent=2)
    merge_leaderboard(f"leaderboard_{a.dataset}.md", rows, a.dataset)
    if a.dataset == "sift":
        # the canonical published leaderboard is the SIFT one
        merge_leaderboard("leaderboard.md", rows, a.dataset)
    print(json.dumps(rows, indent=2))


if __name__ == "__main__":
    main()
